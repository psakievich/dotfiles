#!/usr/bin/env python3
"""Turn `spack env activate --sh` output into a portable load script.

`spack env activate --sh` prints fully expanded values: it captures the PATH,
MANPATH, etc. of the shell that ran it. Sourcing that later replaces the
login shell's variables with a stale snapshot. This filter keeps only what
spack *added*, and prepends it to whatever the variable holds when the
script is sourced:

    export PATH=/view/bin:/usr/bin:/bin     (generated in a shell with PATH=/usr/bin:/bin)
 -> export PATH="/view/bin${PATH:+:$PATH}"

SPACK_* variables and aliases are dropped, so the result does not depend on
the spack environment directory (which lives in the scratch build root).

Usage: spack env activate --sh <env> | make_load_sh.py > load.sh
"""

import os
import re
import shlex
import sys

EXPORT_RE = re.compile(r"^export ([A-Za-z_][A-Za-z0-9_]*)=(.*?);?$")
SEMICOLON_VARS = {"LUA_PATH", "LUA_CPATH"}


def unquote(raw):
    parts = shlex.split(raw)
    return parts[0] if parts else ""


def portable(var, new):
    sep = ";" if var in SEMICOLON_VARS else ":"
    old = os.environ.get(var, "")
    if old and new != old and new.endswith(sep + old):
        added = new[: -len(sep + old)]
        return f'export {var}={shlex.quote(added)}"${{{var}:+{sep}${var}}}"'
    if old and new == old:
        return None  # spack did not change it
    return f"export {var}={shlex.quote(new)}"


def main():
    out = ["# Generated by lib/make_load_sh.py -- do not edit."]
    for line in sys.stdin.read().splitlines():
        m = EXPORT_RE.match(line.strip())
        if not m:
            continue
        var, raw = m.groups()
        if var.startswith("SPACK"):
            continue
        stmt = portable(var, unquote(raw))
        if stmt:
            out.append(stmt)
    print("\n".join(out))


if __name__ == "__main__":
    main()
